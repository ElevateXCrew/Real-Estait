export function DynamicIcon({
  name,
  className,
  size,
  strokeWidth,
}: {
  name: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
}) {
  const Icon = ICONS[name] ?? Sparkles;
  return (
    <Icon
      className={className}
      size={size}
      strokeWidth={strokeWidth ?? 2}
      aria-hidden="true"
    />
  );
}
